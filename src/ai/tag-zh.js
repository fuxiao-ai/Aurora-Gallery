/**
 * 标签 → 中文显示名。查不到返回 `null`（调用方回落英文原文）。
 * 键是**精确匹配**（库内原文，小写下划线），不做分词/去后缀的模糊兜底：
 * 面板上的每个词都应该能反查回 tag 路检索，模糊兜底会造出「看起来是词表词」的假象。
 */
function toZh(tag) {
  if (tag == null) return null;
  var hit = ZH[String(tag)];
  return hit == null ? null : hit;
}

/** 该标签有没有中文映射（守护与统计用）。 */
